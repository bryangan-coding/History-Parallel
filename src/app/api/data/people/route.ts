function hasChinese(text: string): boolean {
  return /[\u4e00-\u9fff\u3400-\u4dbf]/.test(text);
}

function toTraditional(text: string): string {
  let result = '';
  for (const ch of text) result += S2T[ch] || ch;
  return result;
}

function toSimplified(text: string): string {
  // Build reverse map once
  const T2S: Record<string, string> = {};
  for (const [sc, tc] of Object.entries(S2T)) T2S[tc] = sc;
  let result = '';
  for (const ch of text) result += T2S[ch] || ch;
  return result;
}

export async function GET(request: NextRequest) {
  const { searchParams } = request.nextUrl;
  const page = Math.max(1, parseInt(searchParams.get('page') || '1'));
  const limit = Math.min(Math.max(1, parseInt(searchParams.get('limit') || '50')), 200);
  const ids = searchParams.get('ids')?.split(',').filter(Boolean);
  const publishedOnly = searchParams.get('published') !== 'false';
  const query = searchParams.get('q')?.trim();
  const era = searchParams.get('era');
  const status = searchParams.get('status');
  const region = searchParams.get('region');

  // Lookup by IDs
  if (ids && ids.length > 0) {
    const items = await findPeopleByIds(ids);
    return NextResponse.json({ items, total: items.length });
  }

  // Determine if this request needs auth (non-public data access)
  const needsAuth = !publishedOnly || (status && status !== 'all');
  if (needsAuth) {
    const session = await auth();
    if (!session) {
      return NextResponse.json({ error: 'Unauthorized' }, { status: 401 });
    }
  }

  // Build DB query options
  const opts: Parameters<typeof listPeople>[0] = { page, limit };

  if (status && status !== 'all') {
    opts.dataStatus = status;
  } else {
    opts.publishedOnly = true;
  }

  if (region && region !== 'all') {
    opts.regionId = region;
  }

  if (query) {
    // For Chinese queries, also search the other script variant
    if (hasChinese(query)) {
      const alt = toTraditional(query);
      if (alt !== query) {
        opts.query = query;
        opts.queryAlt = alt;
      } else {
        const simplified = toSimplified(query);
        if (simplified !== query) {
          opts.query = query;
          opts.queryAlt = simplified;
        } else {
          opts.query = query;
        }
      }
    } else {
      opts.query = query;
    }
  }

  // Era filter
  if (era) {
    const range = ERA_MAP[era];
    if (range) {
      opts.era = {
        min: range.min,
        max: isFinite(range.max) ? range.max : null,
      };
    }
  }

  const { items, total } = await listPeople(opts);

  return NextResponse.json({
    items,
    total,
    page,
    limit,
    totalPages: Math.ceil(total / limit),
  });
}

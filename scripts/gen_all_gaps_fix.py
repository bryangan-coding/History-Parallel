seq = 0
cur.execute("SELECT COALESCE(MAX(CAST(SUBSTRING_INDEX(id,'-',-1) AS UNSIGNED)),-1)+1 FROM events WHERE id LIKE 'evt-gap-%'")
try: seq = int(cur.fetchone()[0])
except: seq = 0

inserted = 0
for name, title, sy, ey, summary, importance, source_ids, tags in EVENTS:
    cur.execute("SELECT id FROM people WHERE name = %s AND data_status = 'published'", (name,))
    rows = cur.fetchall()
    if not rows: print(f"SKIP: {name}"); continue
    pid = rows[0][0]
    cur.execute("SELECT COUNT(*) FROM events e INNER JOIN event_persons ep ON e.id=ep.event_id WHERE ep.person_id=%s AND e.title=%s", (pid, title))
    if cur.fetchone()[0] > 0: continue
    eid = f"evt-gap-{seq:04d}"; seq += 1
    cur.execute("INSERT INTO events (id,title,start_year,end_year,summary,importance,source_ids,tags,data_status,confidence_score) VALUES (%s,%s,%s,%s,%s,%s,%s,%s,'published',0.93)",
        (eid, title, sy, ey, summary, importance, json.dumps(source_ids), json.dumps(tags)))
    cur.execute("INSERT INTO event_persons (event_id, person_id) VALUES (%s,%s)", (eid, pid))
    inserted += 1

conn.commit()
cur.execute("SELECT COUNT(*) FROM events WHERE data_status='published'")
print(f"Inserted {inserted}. Total: {cur.fetchone()[0]}")
cur.close()
conn.close()

inserted = 0
seq = 0
for name, title, start_year, end_year, summary, importance, source_ids, tags in EVENTS:
    cur.execute("SELECT id FROM people WHERE name = %s AND data_status = 'published'", (name,))
    rows = cur.fetchall()
    if not rows:
        print(f"SKIP (not found): {name}")
        continue
    pid = rows[0][0]
    event_id = f"evt-major-{seq:04d}"
    seq += 1
    
    cur.execute("SELECT COUNT(*) FROM events WHERE id = %s OR (title = %s AND id IN (SELECT event_id FROM event_persons WHERE person_id = %s))",
               (event_id, title, pid))
    if cur.fetchone()[0] > 0:
        print(f"EXISTS: {name} - {title}")
        continue
    
    try:
        cur.execute("INSERT INTO events (id, title, start_year, end_year, summary, importance, source_ids, tags, data_status, confidence_score) VALUES (%s,%s,%s,%s,%s,%s,%s,%s,'published',0.92)",
            (event_id, title, start_year, end_year, summary, importance, json.dumps(source_ids), json.dumps(tags)))
        cur.execute("INSERT INTO event_persons (event_id, person_id) VALUES (%s,%s)", (event_id, pid))
        inserted += 1
    except Exception as e:
        print(f"ERROR: {name} - {e}")

conn.commit()
print(f"\nInserted {inserted} events")


# Delete junk for these figures
for name in names:
    cur.execute("SELECT id FROM people WHERE name = %s AND data_status = 'published'", (name,))
    rows = cur.fetchall()
    if not rows:
        print(f"NOT FOUND: {name}")
        continue
    pid = rows[0][0]
    cur.execute("""
        DELETE e FROM events e
        INNER JOIN event_persons ep ON e.id = ep.event_id
        WHERE ep.person_id = %s AND (
            e.title LIKE '%早期创作%' OR e.title LIKE '%成年立世%' OR e.title LIKE '%成长岁月%'
            OR e.title LIKE '%垂暮之年%' OR e.title LIKE '%文风成熟%' OR e.title LIKE '%文坛影响%'
            OR e.title LIKE '%文学成就%' OR e.title LIKE '%诗歌创作%' OR e.title LIKE '%史料来源%'
            OR e.title LIKE '%诗歌成熟%' OR e.title LIKE '%与%社会%'
        )
    """, (pid,))
    if cur.rowcount > 0:
        print(f"{name}: deleted {cur.rowcount} junk events")

conn.commit()

# Insert new events
inserted = 0
seq = 0
for name, title, start_year, end_year, summary, importance, source_ids, tags in EVENTS:
    cur.execute("SELECT id FROM people WHERE name = %s AND data_status = 'published'", (name,))
    rows = cur.fetchall()
    if not rows: continue
    pid = rows[0][0]
    event_id = f"evt-deep2-{re.sub(r'[^a-z0-9]', '-', name.lower())}-{seq}"
    seq += 1
    cur.execute("SELECT id FROM events WHERE title = %s", (title,))
    if cur.fetchone():
        print(f"EXISTS: {name} - {title}")
        continue
    cur.execute("INSERT INTO events (id, title, start_year, end_year, summary, importance, source_ids, tags, data_status, confidence_score) VALUES (%s,%s,%s,%s,%s,%s,%s,%s,'published',0.9)",
        (event_id, title, start_year, end_year, summary, importance, json.dumps(source_ids), json.dumps(tags)))
    cur.execute("INSERT IGNORE INTO event_persons (event_id, person_id) VALUES (%s, %s)", (event_id, pid))
    inserted += 1

conn.commit()
print(f"\nInserted {inserted} events")

for name in sorted(names):
    cur.execute("SELECT id FROM people WHERE name = %s AND data_status = 'published'", (name,))
    rows = cur.fetchall()
    if rows:
        cur.execute("SELECT COUNT(*) FROM events e INNER JOIN event_persons ep ON e.id=ep.event_id WHERE ep.person_id=%s AND e.data_status='published'", (rows[0][0],))
        print(f"{name}: {cur.fetchone()[0]} events")

cur.close()
conn.close()
print("Done!")
